// وظيفة الملف: يحتوي على إعدادات الاتصال والروابط الخاصة بخدمة الذكاء الاصطناعي (Gemini API).
// علاقته بالمشروع: يجمع جميع الإعدادات الحساسة في مكان واحد لتسهيل الوصول إليها وتعديلها.
// أين يتم استخدامه: يُستخدم بشكل أساسي في ملف gemini_service.dart لإجراء الاتصال بالخادم.
// ============================================================================
//
// ⚠️ تحذير أمني هام (مفهوم متقدم): 
// لا تشارك مفتاح API الخاص بك (API Key) مع أي شخص! 
// في التطبيقات الحقيقية والمرفوعة على المتاجر، يجب ألا تضع مفتاح API داخل كود 
// التطبيق (Frontend) لأنه يمكن استخراجه بسهولة. بدلاً من ذلك، يجب وضعه في 
// خادم خلفي (Backend) والتواصل مع الخادم الخاص بك.
// هنا نستخدم ملف .env كحل مؤقت لحماية المفتاح أثناء التطوير.

// استيراد مكتبة flutter_dotenv التي تسمح لنا بقراءة المتغيرات من ملف مخفي اسمه .env
import 'package:flutter_dotenv/flutter_dotenv.dart';

// ==========================================
// كلاس إعدادات الـ API (ApiConfig)
// ==========================================
// نستخدم كلاس يحتوي على متغيرات ثابتة (static) لكي نتمكن من الوصول إليها 
// من أي مكان في التطبيق بطلب مباشر مثل: ApiConfig.geminiBaseUrl 
// دون الحاجة لإنشاء كائن (Object) من الكلاس.
class ApiConfig {
  
  // دالة لجلب مفتاح Gemini API من ملف .env
  // نستخدم dotenv.env لقراءة الملف. إذا لم يجد المفتاح يُعيد نصاً فارغاً ''.
  static String get geminiApiKey => dotenv.env['GEMINI_API_KEY'] ?? '';

  // رابط الخادم الخاص بـ Gemini للطلبات العادية (إرسال سؤال وانتظار الجواب كاملاً)
  // يُستخدم في: تحليل الشخصية، تحليل المصروفات، أو استخراج البيانات.
  static const String geminiBaseUrl =
      'https://generativelanguage.googleapis.com/v1beta/models/gemini-2.5-flash:generateContent';

  // رابط الخادم الخاص بـ Gemini لطلبات البث (Streaming)
  // البث يعني أن الخادم يرسل الجواب كقطعة صغيرة متتالية (حرفاً حرفاً أو كلمة كلمة)
  // يُستخدم في: شاشة المحادثة (الدردشة) لكي يظهر النص للمستخدم وكأن المساعد يكتبه الآن.
  static const String geminiStreamUrl =
      'https://generativelanguage.googleapis.com/v1beta/models/gemini-2.5-flash:streamGenerateContent';

  // دالة للتحقق مما إذا كان المستخدم قد وضع مفتاح API حقيقي في ملف .env
  // تُرجع true إذا كان المفتاح موجوداً وليس القيمة الافتراضية.
  // يتم استخدامها لتنبيه المستخدم إذا نسي وضع المفتاح.
  static bool get isApiKeySet {
    return geminiApiKey.isNotEmpty &&
        geminiApiKey != 'PUT_YOUR_GEMINI_API_KEY_HERE';
  }
}
