// ============================================================================
// اسم الملف: theme_provider.dart
// وظيفة الملف: يتحكم في مظهر التطبيق (الوضع الليلي والنهاري).
// علاقته بالمشروع: يوفر حالة الثيم لملف main.dart لكي يُطبق الألوان المناسبة.
// أين يتم استخدامه: في main.dart، وفي SettingsScreen للتبديل بين الأوضاع.
// ============================================================================

import 'package:flutter/material.dart';

// ==========================================
// كلاس مزود مظهر التطبيق (ThemeProvider)
// ==========================================
// يرث من ChangeNotifier ليتمكن من تحديث كامل التطبيق عند تغير الثيم.
class ThemeProvider extends ChangeNotifier {
  
  // ==========================================
  // المتغيرات الخاصة (Private Variables)
  // ==========================================
  
  // متغير منطقي (bool) يخزن حالة الثيم: 
  // false = وضع نهاري (Light Mode) وهو الافتراضي
  // true = وضع ليلي (Dark Mode)
  bool _isDarkMode = false;

  // ==========================================
  // دوال القراءة (Getters)
  // ==========================================
  
  // دالة للقراءة فقط تُرجع حالة الثيم الحالية لتستخدمها الشاشات
  bool get isDarkMode => _isDarkMode;

  // ==========================================
  // دوال التعديل (Setters/Actions)
  // ==========================================
  
  // دالة تُستدعى عند ضغط زر "الوضع الليلي" في شاشة الإعدادات
  void toggleTheme() {
    // علامة التعجب (!) هنا تعني "النفي" (NOT)
    // إذا كان الثيم نهاري (false) سيصبح ليلي (true)، والعكس صحيح
    _isDarkMode = !_isDarkMode;
    
    // ⚠️ استدعاء notifyListeners هنا سيجعل ملف main.dart يُعيد بناء 
    // تطبيق MaterialApp بالكامل لاختيار الألوان المناسبة للوضع الجديد.
    notifyListeners(); 
  }
}
