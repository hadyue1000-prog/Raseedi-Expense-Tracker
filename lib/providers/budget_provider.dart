// ============================================================================
// اسم الملف: budget_provider.dart
// وظيفة الملف: يتحكم في قيمة الميزانية الشهرية التي يحددها المستخدم.
// علاقته بالمشروع: يوفر الميزانية المطلوبة لحساب شريط التقدم في الصفحة الرئيسية والإحصائيات.
// أين يتم استخدامه: في HomeScreen، BudgetScreen، AiAssistantProvider.
// ============================================================================

import 'package:flutter/material.dart';

// ==========================================
// كلاس مزود الميزانية (BudgetProvider)
// ==========================================
// يرث من ChangeNotifier ليتمكن من تحديث الشاشات عند تغير الميزانية.
class BudgetProvider extends ChangeNotifier {
  
  // ==========================================
  // المتغيرات الخاصة (Private Variables)
  // ==========================================
  
  // الميزانية الشهرية الافتراضية للمستخدم (مثلاً 2000 ريال)
  // تبدأ بـ "_" لتكون مخفية ولا تتغير إلا عن طريق الدالة المخصصة لذلك
  double _monthlyBudget = 0;

  // ==========================================
  // دوال القراءة (Getters)
  // ==========================================
  
  // دالة للقراءة فقط، تُرجع قيمة الميزانية الحالية لتستخدمها الشاشات (مثل شاشة الرئيسية)
  double get monthlyBudget => _monthlyBudget;

  // ==========================================
  // دوال التعديل (Setters/Actions)
  // ==========================================
  
  // دالة تُستدعى عندما يقوم المستخدم بتعديل ميزانيته من شاشة "الميزانية" (BudgetScreen)
  void updateBudget(double newBudget) {
    // نحدث القيمة المخفية بالقيمة الجديدة
    _monthlyBudget = newBudget;
    
    // ⚠️ استدعاء notifyListeners مهم جداً!
    // يخبر جميع الشاشات (مثل HomeScreen) أن الميزانية تغيرت،
    // فتقوم الشاشات بإعادة رسم نفسها (Rebuild) لتظهر الميزانية الجديدة وشريط التقدم الجديد.
    notifyListeners(); 
  }
}
