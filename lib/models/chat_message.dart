// علاقته بالمشروع: يُستخدم لتنظيم بيانات الدردشة (من أرسل الرسالة؟ متى؟ هل تحتوي على عملية؟).
// أين يتم استخدامه: يتم استخدامه في AiAssistantProvider و AiChatScreen.
