// ==========================================
// كلاس رسالة المحادثة (ChatMessage)
// ==========================================
// ما معنى "Model" هنا؟
// Model هو كلاس يصف شكل البيانات — مثل "قالب" للرسالة.
// كل رسالة تظهر في شاشة المحادثة هي عبارة عن كائن (Object) تم إنشاؤه من هذا القالب.
class ChatMessage {
  
  // نص الرسالة الفعلي (ما كتبه المستخدم أو المساعد الذكي)
  // نوعه String
  final String text;                             

  // هل هذه الرسالة مرسلة من المستخدم أم من المساعد؟
  // نوعه bool (منطقي: true أو false)
  // true = رسالة المستخدم (تظهر على اليمين بلون مختلف)
  // false = رسالة المساعد (تظهر على اليسار)
  final bool isUser;                             

  // بيانات العملية المالية المستخرجة من النص (إن وُجدت)
  // نوعه Map<String, dynamic> (قاموس يحتوي على مفاتيح نصوص وقيم متغيرة)
  // علامة الاستفهام (?) تعني أن هذه القيمة قد تكون null (فارغة) لأن ليست كل رسالة تحتوي على عملية مالية.
  final Map<String, dynamic>? parsedTransaction; 

  // وقت وتاريخ إرسال الرسالة
  // يُستخدم لترتيب الرسائل، ويُستخدم أيضاً كمعرّف فريد (Unique ID) للبحث عن هذه الرسالة لاحقاً
  final DateTime timestamp;                      

  // هل فشل إرسال هذه الرسالة إلى الـ API؟
  // يُستخدم لإظهار رسالة خطأ وزر "إعادة المحاولة" في واجهة المستخدم
  final bool hasFailed;                          

  // هل تم حفظ العملية المالية المرفقة بهذه الرسالة بالفعل في قاعدة البيانات؟
  // يُستخدم لتغيير شكل زر "حفظ" إلى "تم الحفظ" لمنع التكرار
  final bool isSaved;                            

  // ==========================================
  // البنّاء (Constructor)
  // ==========================================
  ChatMessage({
    required this.text,
    required this.isUser,
    this.parsedTransaction,
    DateTime? timestamp, // يمكن تمرير وقت محدد، وإلا سيأخذ الوقت الحالي
    this.hasFailed = false, // افتراضياً: الرسالة لم تفشل
    this.isSaved = false,   // افتراضياً: العملية المرفقة لم تُحفظ بعد
  }) : timestamp = timestamp ?? DateTime.now(); // تعيين الوقت الحالي إذا لم يتم تمريره

  // ==========================================
  // دالة النسخ مع التعديل (copyWith)
  // ==========================================
  // في لغة Dart، المتغيرات المعرفة كـ final لا يمكن تغيير قيمتها بعد إنشائها.
  // فكيف نُعدّل نص الرسالة أثناء تدفق البيانات (Streaming) من الـ API؟
  // الحل هو دالة copyWith: وهي دالة تُنشئ "نسخة جديدة" من الرسالة مع تغيير الحقول المطلوبة فقط، 
  // مع الاحتفاظ بباقي الحقول كما هي.
  // مثال: 
  // رسالة جديدة = الرسالة القديمة.copyWith(text: "النص الجديد");
  ChatMessage copyWith({
    String? text,
    bool? hasFailed,
    bool? isSaved,
    Map<String, dynamic>? parsedTransaction,
  }) {
    return ChatMessage(
      // إذا تم تمرير نص جديد استخدمه، وإلا استخدم النص القديم (this.text)
      text: text ?? this.text,
      // isUser لا يتغير أبداً
      isUser: isUser,
      parsedTransaction: parsedTransaction ?? this.parsedTransaction,
      timestamp: timestamp,
      hasFailed: hasFailed ?? this.hasFailed,
      isSaved: isSaved ?? this.isSaved,
    );
  }
}
