// هذا الكلاس يمثل المستخدم في التطبيق
// لماذا نستخدم Model؟
// بدلاً من تمرير الاسم (String) والإيميل (String) بشكل منفصل لكل شاشة، 
// نجمعها في "قالب" واحد (Object) يسمى UserModel لسهولة التعامل معها وترتيب الكود.
class UserModel {
  
  // ==========================================
  // الخصائص (Properties)
  // ==========================================
  
  // اسم المستخدم
  // نوع البيانات String (نص)
  // يتم استخدامه لعرض رسالة الترحيب في الشاشة الرئيسية (Home Screen)
  final String name; 
  
  // البريد الإلكتروني للمستخدم
  // نوع البيانات String (نص)
  // يُستخدم لتعريف المستخدم (كمعرف فريد) في النظام
  final String email;

  // ==========================================
  // البنّاء (Constructor)
  // ==========================================
  
  // هذه الدالة (Constructor) تُستدعى عند إنشاء مستخدم جديد في الكود
  // كلمة required تعني أنه لا يمكن إنشاء مستخدم بدون إعطاء اسم وإيميل.
  // مثال على الاستخدام: UserModel user = UserModel(name: 'أحمد', email: 'ahmed@test.com');
  UserModel({
    required this.name, 
    required this.email
  });
}
