// ============================================================================
// اسم الملف: transaction_model.dart
// وظيفة الملف: يحتوي على نموذج (Model) يمثل العملية المالية (سواء كانت دخل أو مصروف).
// علاقته بالمشروع: هذا هو الهيكل الأساسي للبيانات في التطبيق، فالتطبيق بأكمله يدور حول "العمليات".
// أين يتم استخدامه: يُستخدم في TransactionProvider، وفي الشاشات التي تعرض العمليات مثل 
//                  HomeScreen و TransactionsScreen و StatisticsScreen.
// ============================================================================

// تعريف أنواع العمليات المتاحة في التطبيق (Enum)
// لماذا نستخدم enum؟
// بدلاً من كتابة النوع كنص String (مثلاً "income" أو "expense") والذي قد نخطئ في كتابته إملائياً،
// نستخدم enum لحصر الخيارات المتاحة، مما يمنع الأخطاء البرمجية ويجعل الكود أسهل في القراءة.
enum TransactionType { 
  income, // يمثل الدخل (إضافة رصيد)
  expense // يمثل المصروف (خصم من الرصيد)
}

// ==========================================
// كلاس العملية المالية (TransactionModel)
// ==========================================
// هذا الكلاس يمثل عملية مالية واحدة في النظام.
// نستخدم Model لتجميع كل تفاصيل العملية (المبلغ، التاريخ، النوع، إلخ) في كائن واحد (Object).
class TransactionModel {
  
  // معرف فريد للعملية (Unique ID)
  // نوعه String، ونستخدمه للبحث عن العملية لتعديلها أو حذفها
  final String id;          

  // عنوان العملية (مثلاً: راتب، غداء، بنزين)
  // نوعه String، يُعرض كعنوان رئيسي في القوائم
  final String title;       

  // قيمة العملية (المبلغ)
  // نوعه double (رقم عشري) لأنه قد يحتوي على كسور
  final double amount;      

  // التصنيف الخاص بالعملية (مثلاً: أكل، مواصلات، دراسة)
  // نوعه String، ويستخدم لاحقاً في شاشة الإحصائيات (StatisticsScreen) لتجميع المصروفات حسب التصنيف
  final String category;    

  // ملاحظة إضافية اختيارية
  // نوعه String، تفيد المستخدم في تذكر تفاصيل العملية
  final String note;        

  // نوع العملية (هل هي دخل أم مصروف؟)
  // نوعه TransactionType (الـ enum الذي عرفناه في الأعلى)
  // بناءً عليه نحدد لون العملية (أخضر للدخل، أحمر للمصروف) وعملية الحساب (+ أو -)
  final TransactionType type; 

  // تاريخ ووقت تسجيل العملية
  // نوعه DateTime، يُستخدم لعرض متى تمت العملية ولترتيب العمليات من الأحدث للأقدم
  final DateTime date;      

  // ==========================================
  // البنّاء (Constructor)
  // ==========================================
  // نستخدمه لإنشاء كائن (Object) جديد يمثل عملية مالية.
  // كلمة required تعني أنه إجباري إدخال جميع هذه القيم عند إنشاء أي عملية جديدة.
  TransactionModel({
    required this.id,
    required this.title,
    required this.amount,
    required this.category,
    required this.note,
    required this.type,
    required this.date,
  });
}
